#pragma once                     // 预处理器指令：确保此头文件在编译时只被包含一次，避免重复定义

/**
 * @file path_utils.h
 * @brief 路径工具函数集
 *
 * 作用：提供文件路径解析相关的工具函数，包括：
 *       - 获取环境变量
 *       - 获取可执行文件目录
 *       - 构建默认搜索路径列表
 *       - 在多个候选路径中解析出第一个存在的绝对路径
 *       这些函数主要用于在不同部署环境下定位配置文件和资源文件。
 */

#include <string>                // 包含标准字符串库，用于std::string类型
#include <vector>                // 包含标准向量库，用于std::vector容器

// ============================================================================
// get_env_or_empty —— 获取环境变量值
// ============================================================================
// 作用：安全地获取环境变量的值。如果环境变量不存在或传入空指针，返回空字符串。
// @param name 环境变量名称
// @return 环境变量的值（字符串），不存在则返回空字符串
// ============================================================================
std::string get_env_or_empty(const char *name);

// ============================================================================
// executable_dir —— 获取可执行文件所在目录
// ============================================================================
// 作用：通过读取 Linux /proc/self/exe 符号链接获取当前可执行文件的绝对路径，
//       然后提取其父目录。失败时回退到当前工作目录。
// @return 可执行文件所在目录的绝对路径
// ============================================================================
std::string executable_dir();

// ============================================================================
// default_search_roots —— 获取默认搜索根路径列表
// ============================================================================
// 作用：构建一个按优先级排序的搜索根目录列表，用于查找配置文件或资源。
//       搜索顺序：
//       1. 环境变量 MYDEMO_ASSET_ROOT 指定的目录（最高优先级）
//       2. 当前工作目录及其上级目录（最多两级）
//       3. 可执行文件所在目录及其上级目录（最多两级）
// @return 去重后的搜索根目录列表
// ============================================================================
std::vector<std::string> default_search_roots();

// ============================================================================
// resolve_existing_path —— 解析存在的绝对路径
// ============================================================================
// 作用：根据给定的相对路径候选列表和可选的环境变量，在默认搜索根目录下
//       查找第一个实际存在的文件，返回其规范化的绝对路径。
//       如果所有候选路径都不存在，回退返回第一个候选路径（不检查存在性）。
// @param relative_candidates 相对路径候选列表
// @param env_var 可选的环境变量名，用于指定基础目录（最高优先级）
// @return 解析后的绝对路径字符串，无候选则返回空字符串
// ============================================================================
std::string resolve_existing_path(const std::vector<std::string> &relative_candidates,
                                  const char *env_var = nullptr);

// ============================================================================
// resolve_config_path —— 解析配置文件路径（简化版）
// ============================================================================
// 作用：resolve_existing_path 的简化封装，仅传入单个文件名。
// @param filename 配置文件名
// @param env_var 可选的环境变量名
// @return 解析后的配置文件绝对路径
// ============================================================================
std::string resolve_config_path(const std::string &filename, const char *env_var = nullptr);
