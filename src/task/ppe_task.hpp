#ifndef PPE_TASK_H
#define PPE_TASK_H

// =====================================================================
// 头文件引用
// =====================================================================
#include "base_task.h"          // 复用其数据结构/队列定义（注：本类并不继承 BaseTask，仅 include 头文件）
#include <iostream>             // 标准输入输出流
#include <atomic>               // 原子操作，用于线程安全的状态标志
#include <memory>               // 智能指针（shared_ptr等）
#include "opencv2/opencv.hpp"   // OpenCV图像处理库
#include "DmaBufferPool.h"      // DMA缓冲池，管理零拷贝图像传输
#include "easy_timer.h"         // 计时器工具，用于性能测量
#include "common.hpp"           // 通用类型定义（DetectContext等）
#include "yolo11_model.hpp"     // YOLO11目标检测模型，支持NPU加速推理
#include "frame_queue.h"        // 帧队列，用于视频帧缓冲
#include <thread>               // C++11线程支持
#include <atomic>               // 原子操作（重复包含，保留原代码）
#include "task_config.hpp"      // 任务配置结构体
#include "BlockingQueue.hpp"    // 阻塞队列，实现生产者-消费者模式
#include "task_data.h"          // 任务数据结构定义

// =====================================================================
// PpeTask类 - PPE检测推理任务
// =====================================================================
// 作用：执行个人防护装备（PPE）检测的推理任务
// 采用生产者-消费者模式，通过阻塞队列接收任务
// 在独立线程中执行YOLO11模型推理，支持NPU加速
//
// 审查注记（与 HelmetTask/BaseTask 的关系 + 生命周期陷阱）：
//   - 本类**不继承** BaseTask（尽管 include 其头文件），是独立实现的
//     完整任务：持有自己的 YOLO11Model 实例与专属推理线程，
//     与 helmet_task（无状态静态方法、跑在 ThreadPool 上）是两种模式；
//   - taskQueue_ 为裸指针（new/delete 手工管理），仅在 init() 创建：
//     start() 之前调用 put()/requestStop() 之外的路径会解引用空指针；
//   - stopBestEffort() 超时 detach 后，析构函数仍会 delete taskQueue_，
//     若在途 run() 线程尚未退出即访问已释放队列 → use-after-free 隐患。
//     因此生产方（ffmpeg_video_decoder）对任务采取"只停不删"策略，
//     对象生命周期上抛给退出流程，勿随手 delete 曾 stopBestEffort 的实例。
// =====================================================================
class PpeTask
{
private:
    // =================================================================
    // 私有成员变量
    // =================================================================
    std::shared_ptr<YOLO11Model> model_;                // YOLO11模型实例（NPU推理引擎）；shared_ptr，析构自动释放（但模型自身无析构，见 yolo11_model.hpp 泄漏注记）
    BlockingQueue<std::shared_ptr<TaskData>>* taskQueue_; // 任务队列指针（生产者-消费者模式）；裸指针：init() 中 new、析构中 delete，非线程安全的所有权
    std::thread thread_;                                // 推理工作线程
    std::atomic<bool> running_{false};                  // 运行状态标志（原子操作保证线程安全）；false 时 run() 在每次 pop 前后检查退出
    std::atomic<bool> finished_{false};                 // 线程完成标志（原子操作保证线程安全）；仅由 run() 出口写 true，stopBestEffort 轮询它决定是否可安全 join
    TaskConfig config;                                  // 任务配置（模型路径、核心分配等）；构造时拷贝一份，init() 后不再变更

public:
    // =================================================================
    // 构造函数
    // =================================================================
    // 作用：创建PPE任务实例，传入配置参数
    // 参数：
    //   config - 任务配置，包含模型路径和NPU核心分配
    // =================================================================
    PpeTask(TaskConfig config);

    // =================================================================
    // 析构函数
    // =================================================================
    // 作用：清理资源，确保线程正确退出
    // =================================================================
    ~PpeTask();

    // =================================================================
    // init - 初始化任务
    // =================================================================
    // 作用：初始化模型和队列，准备执行推理
    // =================================================================
    void init();

    // =================================================================
    // start - 启动推理线程
    // =================================================================
    // 作用：启动独立线程执行推理任务
    // 线程将从任务队列中获取任务并执行推理
    // =================================================================
    void start();

    // =================================================================
    // put - 提交任务到队列
    // =================================================================
    // 作用：将任务数据放入阻塞队列，供推理线程处理
    // 参数：
    //   task - 任务数据智能指针，包含待推理的图像
    // 线程安全：BlockingQueue保证多线程安全访问
    // 时序约束：taskQueue_ 在 init()（start() 内部调用）才创建，
    //           start() 之前调用本函数会解引用空指针 → 崩溃
    // =================================================================
    void put(std::shared_ptr<TaskData> task);

    // =================================================================
    // requestStop - 请求停止（非阻塞）
    // =================================================================
    // 作用：请求停止推理线程，不阻塞当前调用
    // 通过关闭队列唤醒线程，让线程自然退出
    // =================================================================
    void requestStop();

    // =================================================================
    // join - 等待线程退出（阻塞）
    // =================================================================
    // 作用：等待推理线程完全退出
    // 注意：可能阻塞较长时间，不要在UI线程直接调用
    // =================================================================
    void join();

    // =================================================================
    // stop - 停止任务（阻塞）
    // =================================================================
    // 作用：停止推理线程并等待其退出
    // =================================================================
    void stop();

    // =================================================================
    // stopBestEffort - 有界停止（最大等待时间）
    // =================================================================
    // 作用：尝试在指定时间内停止线程，超时后强制分离
    // 参数：
    //   waitMs - 最大等待时间（毫秒），默认1500ms
    // 保证UI线程不会因等待而卡死
    // =================================================================
    void stopBestEffort(int waitMs = 1500);

    // =================================================================
    // reloadModel - 热更新模型
    // =================================================================
    // 作用：在不停止整个系统的情况下替换推理模型
    // 流程：
    //   1. 停止当前推理线程
    //   2. 销毁旧模型（释放 NPU 资源）
    //   3. 创建新模型
    //   4. 重启推理线程
    // 参数：
    //   newPath - 新模型文件路径
    //   newLabelPath - 新标签文件路径
    //   coreMask - NPU 核心掩码
    // 返回：true=成功，false=失败（旧模型继续工作）
    // =================================================================
    bool reloadModel(const std::string &newPath,
                     const std::string &newLabelPath,
                     rknn_core_mask coreMask);

    // =================================================================
    // getModelPath - 获取当前模型路径
    // =================================================================
    std::string getModelPath() const { return config.modelPath; }

private:
    // =================================================================
    // run - 推理线程主函数
    // =================================================================
    // 作用：执行推理循环，从队列获取任务并处理
    // 循环检查running_标志，直到请求停止
    // =================================================================
    void run();
};

#endif //PPE_TASK_H
