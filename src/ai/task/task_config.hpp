#ifndef TASK_CONFIG_H
#define TASK_CONFIG_H


// =====================================================================
// 头文件引用
// =====================================================================
#include <string>               // 字符串类
#include <rknn_api.h>           // RKNN NPU推理API

// =====================================================================
// TaskConfig结构体 - 任务配置
// =====================================================================
// 作用：定义推理任务的配置参数
// 包含模型路径、标签路径和NPU核心分配
//
// 说明：本结构是"值语义"的配置快照——PpeTask 构造时整体拷贝一份，
// 之后修改外部副本不会影响已启动的任务；字段无校验，
// 路径错误在 YOLO11Model 构造（init）时才以 throw/返回失败暴露。
// =====================================================================
struct TaskConfig
{
    std::string modelPath;      // RKNN模型文件路径（.rknn格式）
    std::string labelPath;      // 标签文件路径，用于检测结果映射
    rknn_core_mask core_mask;   // NPU核心掩码，指定在哪个NPU核心上运行
                                // RK3588有3个NPU核心，可通过掩码选择特定核心
                                // 注意它是**位掩码枚举**（CORE_0=1<<0、
                                // CORE_1=1<<1、CORE_2=1<<2、AUTO=0），
                                // 不是序号：ffmpeg_video_decoder 多任务轮派
                                // 用 `RKNN_NPU_CORE_0 + (idx % 3)` 得到 1/2/4
                                // 三选一轮转——依赖位值恰好连续递增这一
                                // rknn_api 细节，语义上等价于查表，改用时
                                // 勿当成普通 int 做加减；
                                // 传 0/AUTO 则由驱动自行选核。
    int result_id = 0;          // 结果路由ID，写入 od_results.id
                                // 摄像头预览多检测器用它区分结果来源
                                // （同一条结果队列多路复用，消费端按 id 选槽位；
                                //  主流水线单检测器保持默认 0）
};

#endif
