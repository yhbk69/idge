#pragma once

// ============================================================================
// fence_checker.h - 电子围栏检测判断
// ============================================================================
//
// 核心功能：
//   1. 判断一个点是否在围栏形状内（射线法）
//   2. 将检测框从模型空间（640x640）映射到原始视频空间
//   3. 把检测框脚点（帧坐标）归一化，与同样是归一化坐标的围栏比较
//   4. 综合判断检测目标是否违反围栏规则
//
// 坐标空间说明：
//   模型空间:     YOLO 推理输出的坐标，固定 640x640
//   原始视频空间: 解码后的视频帧分辨率（如 1920x1080）
//   归一化空间:   视频内容区按 0..kFenceNormBase 归一（见 fence_shape.h）。
//                 判定端**不需要知道任何 widget 几何**：overlay 尺寸、视图模式、
//                 全屏与否都不参与，所以换视图不会让既有围栏改语义。
//
// 判断逻辑（按形状角色，见 FenceRole）：
//   取检测框的"底边中点"（脚部位置），判断该点落在哪个角色里。
//   - 禁区 Forbidden:  脚点在任一带禁区角色的围栏内 → Intrusion（闯入）
//   - 岗区域 Workzone: 该通道有岗区域、且脚点在所有岗区域之外 → Absence（离岗）
//   两条规则的归并方向相反，于是逐形状判定，不再有一个全局 mode 开关。
//   （旧 geofence.mode 的 inside_alarm/outside_alarm 已退役，只在加载时用作
//    给老配置补角色的依据，之后每个形状自带角色。）
//
// ============================================================================

#include "fence_shape.h"
#include "common.hpp"

namespace geofence {

// ============================================================================
// FenceVerdict / FenceViolation - 单个目标对一个通道围栏表的裁决结果
// ============================================================================
// 之所以返回一个结构而不是 bool：禁区与岗区域的违规条件不是彼此的补集
// （"不在任何岗区域内"与"不在任何禁区内"可以同时成立），调用方需要知道
// 报的是哪一种，才能给报警分类、给事件表分角色。
//
// verdict:    None = 不违规；Intrusion = 闯入禁区；Absence = 离岗
// role:       与 verdict 对应的形状角色，直接喂给解码器的事件表做分角色去重
// shapeIndex: Intrusion 时命中的那个禁区形状下标；Absence 恒为 -1，
//             因为"在所有岗区域之外"是对整张表的负向推断，没有单一责任形状。
// ============================================================================
enum class FenceVerdict {
    None,
    Intrusion,  // 闯入禁区
    Absence     // 离岗：人在所有岗区域之外
};

struct FenceViolation {
    FenceVerdict verdict = FenceVerdict::None;
    FenceRole role = FenceRole::Forbidden;
    int shapeIndex = -1;
};

class FenceChecker {
public:
    // ========================================================================
    // 点是否在矩形内
    // ========================================================================
    static bool pointInRect(int x, int y, const Rectangle &rect);

    // ========================================================================
    // 点是否在多边形内（射线法 / crossing number）
    // 原理：从测试点向右发射水平射线，统计与多边形各边的穿越次数，
    //       奇数=内部，偶数=外部。时间复杂度 O(n)，n 为顶点数。
    // 特性：天然支持凹多边形（凹口处穿越次数自动抵消，不会误判）。
    // 边界：射线判定条件用 (yi>y)!=(yj>y) 的半开区间写法规避顶点重复计数；
    //       落在边/顶点上的点属于退化情形，结果不保证严格一致（对像素级围栏可接受）。
    // ========================================================================
    static bool pointInPolygon(int x, int y, const std::vector<Point> &polygon);

    // ========================================================================
    // 点是否在形状内（自动判断矩形/多边形）
    // ========================================================================
    static bool pointInShape(int x, int y, const FenceShape &shape);

    // ========================================================================
    // 将检测框从模型空间映射到原始视频空间
    // box:        模型输出的检测框（640x640）
    // srcW/srcH:  原始视频分辨率
    // modelW/H:   模型输入尺寸（通常 640x640）
    // ========================================================================
    static void mapBoxToOriginal(const image_rect_t &box,
                                 int srcW, int srcH,
                                 int modelW, int modelH,
                                 int &outLeft, int &outTop,
                                 int &outRight, int &outBottom);

    // ========================================================================
    // 判断单个检测目标是否在围栏内
    // 算法：取检测框"底边中点"作为脚点（帧坐标），按 srcW/srcH 归一到
    //       0..kFenceNormBase，再与同样是归一化坐标的围栏比较。
    //       不再需要 overlay 尺寸 —— 判定与 widget 几何彻底无关。
    // srcW/srcH: 原始视频帧尺寸，同时是归一化的除数；<=0 时脚点落到 0，
    //            等价于"这一帧尺寸不可信"，不会误判成命中。
    // ========================================================================
    static bool isInsideFence(const object_detect_result &det,
                              int srcW, int srcH,
                              int modelW, int modelH,
                              const FenceShape &fence);

    // ========================================================================
    // 综合判断：检测目标违反了哪个角色的围栏规则
    //
    // 单遍扫描该通道形状，按下面顺序出结论（**禁区优先，一人一帧一条**）：
    //   1. 命中任一带 Forbidden 角色的形状      → {Intrusion, Forbidden, idx}
    //   2. 否则本通道有岗区域、且不在任一带 Workzone 角色的形状内
    //                                          → {Absence, Workzone, -1}
    //   3. 否则                                → None
    // 取禁区优先的理由：禁区命中是一条正向的几何事实，离岗是对整张形状表的
    // 负向推断。同一具身体既落在禁区里又落在岗区域外时发两条报警，会把一次
    // 现场事件拆成两次处置，而其中更可处置的正是"他闯进了禁区"。
    //
    // 推论（容易读错，写明）：岗区域是"在所有岗区域之外"，不是逐区域判定 ——
    // 人在任一岗区域内就不算离岗，即使他同时不在第二个岗区域内。
    //
    // 通道未启用或一个形状都没有时返回 None（围栏不参与过滤）。
    // ========================================================================
    static FenceViolation checkDetection(const object_detect_result &det,
                                         int srcW, int srcH,
                                         int modelW, int modelH,
                                         const ChannelFence &channelFence);
};

} // namespace geofence
